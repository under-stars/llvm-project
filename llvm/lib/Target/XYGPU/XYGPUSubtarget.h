#ifndef LLVM_LIB_TARGET_XYGPU_XYGPUSubtarget_H
#define LLVM_LIB_TARGET_XYGPU_XYGPUSubtarget_H

#include "XYGPUFrameLowering.h"
#include "XYGPUInstrInfo.h"
#include "XYGPURegisterInfo.h"

#define GET_SUBTARGETINFO_HEADER
#include "XYGPUGenSubtargetInfo.inc"

namespace llvm {
class StringRef;

class XYGPUSubtarget : public XYGPUGenSubtargetInfo {
private:
  virtual void anchor();

  XYGPURegisterInfo RegInfo;

public:
  // Initializes the data members to match that of the specified triple.
  XYGPUSubtarget(const Triple &TT, StringRef GPU, StringRef FS,
                 const TargetMachine &TM);

  // Parses features string setting specified subtarget options. The
  // definition of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef GPU, StringRef TuneGPU, StringRef FS);

  /// Initializes using the passed in GPU and feature strings so that we can
  /// use initializer lists for subtarget initialization.
  XYGPUSubtarget &initializeSubtargetDependencies(StringRef GPU, StringRef FS,
                                                  const TargetMachine &TM);

  const XYGPURegisterInfo *getRegisterInfo() const override { return &RegInfo; }
};
} // end namespace llvm

#endif