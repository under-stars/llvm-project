#ifndef LLVM_LIB_TARGET_XYGPU_MCTARGETDESC_XYGPUINSTPRINTER_H
#define LLVM_LIB_TARGET_XYGPU_MCTARGETDESC_XYGPUINSTPRINTER_H

#include "MCTargetDesc/XYGPUMCTargetDesc.h"
#include "llvm/MC/MCInstPrinter.h"

namespace llvm {
class XYGPUInstPrinter : public MCInstPrinter {
public:
  XYGPUInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                   const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O,
                    const char *Modifier = nullptr);
  void printRegularOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printPred(const MCInst *MI, raw_ostream &O);
  void printControlCode(const MCInst *MI, raw_ostream &O);
  void dummyPrint(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printGeneralInstruction(const MCInst *MI, raw_ostream &O);
  void printMnemonic(const MCInst *MI, raw_ostream &O);
  void printInstrModis(const MCInst *MI, raw_ostream &O);
#define INST_PRINTER_FUNCS_DECLARATION
#include "AutoGen/XYGPUInstPrinter.inc"
#undef INST_PRINTER_FUNCS_DECLARATION

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  bool printAliasInstr(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg, unsigned AltIdx);
  static const char *getRegisterName(MCRegister Reg);
};
} // end namespace llvm

#endif